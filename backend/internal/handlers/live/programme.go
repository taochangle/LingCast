// Rotation is shared by both API services and isolated by broadcast, never by viewer.
func (h *LiveHandler) programmeSpeech(ctx context.Context, avatarID uint, revision int64, kind string) string {
	scripts := append([]string(nil), programmeScripts[kind]...)
	if len(scripts) == 0 {
		return ""
	}
	fingerprint := tokenDigest(strings.Join(scripts, "\n"))[:12]
	rand.Shuffle(len(scripts), func(i, j int) { scripts[i], scripts[j] = scripts[j], scripts[i] })
	key := fmt.Sprintf("live_programme:%d:%d:%s:%s", avatarID, revision, kind, fingerprint)
	speech, err := h.q.PopRotation(ctx, key, scripts, 24*time.Hour)
	if err != nil {
		return ""
	}
	return speech
}
